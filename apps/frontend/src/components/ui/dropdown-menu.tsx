/** Radix positions with `transform`, which kills backdrop-filter — convert to top/left. */
function useBackdropSafePosition(ref: React.RefObject<HTMLElement | null>) {
  React.useLayoutEffect(() => {
    const el = ref.current
    if (!el) return

    const sync = () => {
      const transform = el.style.transform
      if (!transform || transform === "none") return
      const match =
        transform.match(/translate3d\(\s*([^,]+),\s*([^,]+)/) ??
        transform.match(/translate\(\s*([^,]+),\s*([^)]+)/)
      if (!match) return
      const x = match[1]!.trim()
      const y = match[2]!.trim()
      el.style.transform = "none"
      el.style.left = x
      el.style.top = y
    }

    sync()
    const observer = new MutationObserver(sync)
    observer.observe(el, { attributes: true, attributeFilter: ["style"] })
    return () => observer.disconnect()
  })
}

function DropdownMenu({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Root>) {
  return <DropdownMenuPrimitive.Root data-slot="dropdown-menu" {...props} />
}

function DropdownMenuPortal({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Portal>) {
  return (
    <DropdownMenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />
  )
}

function DropdownMenuTrigger({
  className,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Trigger>) {
  return (
    <DropdownMenuPrimitive.Trigger
      data-slot="dropdown-menu-trigger"
      className={cn("zarva-dropdown-trigger", className)}
      {...props}
    />
  )
}

function DropdownMenuContent({
  className,
  align = "start",
  sideOffset = 4,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content>) {
  const ref = React.useRef<HTMLDivElement>(null)
  useBackdropSafePosition(ref)

  return (
    <DropdownMenuPrimitive.Portal>
      <DropdownMenuPrimitive.Content
        ref={ref}
        data-slot="dropdown-menu-content"
        sideOffset={sideOffset}
        align={align}
        className={cn(
          'zarva-glass-popover z-50 max-h-(--radix-dropdown-menu-content-available-height) w-(--radix-dropdown-menu-trigger-width) min-w-32 p-1 zarva-scrollbar duration-150 data-open:animate-in data-open:fade-in-0 data-closed:animate-out data-closed:fade-out-0',
          className,
        )}
        {...props}
      />
    </DropdownMenuPrimitive.Portal>
  )
}

