const fs = require('fs');
const path = require('path');

const msgDir = 'E:/main-projects/zarva/apps/frontend/messages';

function read(name) {
  return JSON.parse(fs.readFileSync(path.join(msgDir, name), 'utf8'));
}

function write(name, data) {
  fs.writeFileSync(path.join(msgDir, name), JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log('updated', name);
}

